#!/bin/sh
# unproved-baseline: how fast the same model decodes when nothing is proved.
#
#   tools/drivers/unproved-baseline.sh <host> <prover-commit> <harness-commit>
#
# Llama-3.1-8B-Instruct on the card, prefilling the prompt and decoding 512
# tokens at two contexts and a ladder of batch sizes, with nothing proved about
# any of it. Each point records three rates, positions per second over their
# own positions: the prefill alone, the decode alone, and the two end to end.
# None of them is an overhead denominator: the paper quotes cost per proved
# position and the reader applies their own prompt and generation mix (the
# decision of 2026-09-08 in docs/decisions/). What the run has to be is honest
# about the machine and the arithmetic: the same card, the same weights, the
# same context lengths as the proved rows, and a backend a reader would
# actually deploy.
#
# Two backends, and they answer different questions. The one that ships with the
# model library is what a reader gets by loading the model and calling it; the
# serving engine is what a reader gets by deploying it, and is much faster at
# batch. Both are measured here where they can be, and neither is presented as
# the other.
#
# The serving engine needs an environment of its own, which is built here and
# never committed. If it cannot be built or cannot run, the run records that and
# keeps the rows it did measure: a baseline that names one backend and says the
# other is missing is worth more than no baseline.
#
# This is a harness run and not a prover run. Nothing here proves anything, so
# its outputs carry no binding table and no proof digest, and its manifest says
# `kind` `harness` and names no prover commit (issue #51). The prover commit
# argument is unused.
#
# The harness commit must be one whose outputs carry a provenance block
# (zk-prover pull request 63).
#
# The first call pushes zk-prover at the harness commit to the host, starts the
# job detached and prints the poll command. Every later call with the same
# arguments prints the status; once the status says done it fetches the outputs
# into runs/<run-id>/, writes manifest.json from the harness's provenance block,
# and runs check.py. Nothing measured is typed in here.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=unproved-baseline
. "$HERE/lib/driver.sh"

# ---- the configuration: here and in the manifest, nowhere else ---------------
LABEL=baseline             # an unproved measurement: the comparison, not the claim
MODEL=${ZK_MODEL:-unsloth/Llama-3.1-8B-Instruct}
DEVICE=cuda
DTYPE=bfloat16
CONTEXTS="4096 16384"      # the two the proved rows are measured at
BATCHES="1 2 4 8 16"       # one is the single-stream row; the rest are the ladder
NEW_TOKENS=512             # the same 512 output tokens the proved sequence decodes
REPS=3; WARMUP=1
XTHREADS=20
# The backend that ships with the model library, and the serving engine. The
# first needs nothing this host does not have; the second is built below.
BACKENDS="hf vllm"

drv_finish "$(drv_status)"

# ---- start: push the pinned harness, then the job ----------------------------
drv_check_commits
BUILD="build/$(printf '%.12s' "$HARNESS")"
drv_push "$BUILD/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
HSRC=\$B/harness-src/harness
OUT=\$R/out
WORK=\$R/work
mkdir -p \$OUT \$WORK
$(drv_job_preamble)
export ZK_MODEL=$MODEL ZK_DEVICE=$DEVICE ZK_THREADS=$XTHREADS
export ZK_BASELINE_OUT=\$WORK
PY="uv run --project \$HSRC \$UVG python"

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
st "harness: \$(cat \$B/harness-src/.source-commit)"

# 1. the harness at its pinned commit, on the CUDA torch
( cd \$HSRC && uv sync --frozen \$UVG )

WEIGHTS=\$( cd \$HSRC && \$PY - <<'PY'
import json, os, time
t0 = time.time()
from huggingface_hub import snapshot_download
p = snapshot_download(os.environ["ZK_MODEL"])
n = sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(p) for f in fs)
print(json.dumps({"bytes": n, "seconds": round(time.time() - t0, 1)}))
PY
)
st "weights: \$WEIGHTS"

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "$LABEL", "kind": "harness",
 "model": "$MODEL", "device": "$DEVICE", "dtype": "$DTYPE",
 "contexts": "$CONTEXTS", "batches": "$BATCHES", "new_tokens": $NEW_TOKENS,
 "reps": $REPS, "warmup": $WARMUP, "backends": "$BACKENDS",
 "weights": \$WEIGHTS,
 "note": "Nothing here is proved. These are the rows a proved rate is divided by."}
CFG

CTXARGS=""; for c in $CONTEXTS; do CTXARGS="\$CTXARGS --context \$c"; done
BATCHARGS=""; for b in $BATCHES; do BATCHARGS="\$BATCHARGS --batch \$b"; done

# 2. the backend that ships with the model library
st "hf: contexts $CONTEXTS, batches $BATCHES"
T0=\$(date +%s)
if ( cd \$HSRC && \$PY -m harness.eval.baseline.decode_bench --backend hf \
     --model $MODEL --dtype $DTYPE --device $DEVICE \
     \$CTXARGS \$BATCHARGS --new-tokens $NEW_TOKENS --reps $REPS --warmup $WARMUP ); then
  st "hf done in \$(( \$(date +%s) - T0 ))s"
else
  printf 'hf\n' >> \$OUT/refused.txt
  st "hf did not run; recorded in out/refused.txt"
fi

# 3. the serving engine, in an environment of its own.  It is built here and
#    never committed; if it will not build on this host, that is recorded and
#    the rows above still stand.
st "vllm: building an environment for it"
T0=\$(date +%s)
if ( cd \$B && uv venv --python 3.12 .venv-vllm >/dev/null 2>&1 \
     && uv pip install --python .venv-vllm --quiet vllm transformers >/dev/null 2>&1 ); then
  st "vllm environment built in \$(( \$(date +%s) - T0 ))s"
  st "vllm: contexts $CONTEXTS, batches $BATCHES"
  T0=\$(date +%s)
  if ( cd \$B && PYTHONPATH=\$B/harness-src ZK_BASELINE_OUT=\$WORK \
       ./.venv-vllm/bin/python -m harness.eval.baseline.decode_bench --backend vllm \
       --model $MODEL --dtype $DTYPE --device $DEVICE \
       \$CTXARGS \$BATCHARGS --new-tokens $NEW_TOKENS --reps $REPS --warmup $WARMUP ); then
    st "vllm done in \$(( \$(date +%s) - T0 ))s"
  else
    printf 'vllm run\n' >> \$OUT/refused.txt
    st "vllm did not run; recorded in out/refused.txt"
  fi
else
  printf 'vllm environment\n' >> \$OUT/refused.txt
  st "the vllm environment did not build; recorded in out/refused.txt"
fi

# 4. what the run delivers: one record per (backend, context, batch)
cp \$WORK/*.json \$OUT/ 2>/dev/null || true
du -sh \$OUT | awk '{print "fetched size: " \$1 "  " \$2}'

# 5. the gate: the first backend must have measured every point asked for, and
#    every record must say where it came from.
python3 - \$OUT "$CONTEXTS" "$BATCHES" $NEW_TOKENS <<'PY'
import glob, json, os, pathlib, sys
out = pathlib.Path(sys.argv[1])
contexts = [int(x) for x in sys.argv[2].split()]
batches = [int(x) for x in sys.argv[3].split()]
new = int(sys.argv[4])
bad, rows = [], []
for f in sorted(out.glob("*.json")):
    if f.name == "config.json":
        continue
    d = json.loads(f.read_text())
    if "provenance" not in d:
        bad.append(f"{f.name} carries no provenance block")
        continue
    p, m = d["provenance"], d.get("measured")
    be = d.get("backend", {}).get("name", p.get("decode_backend"))
    run = d.get("run", {})
    if m:
        rates = {k: m.get(f"pos_s_{k}_per_stream") for k in ("prefill", "decode", "end_to_end")}
        if any(v is None for v in rates.values()):
            bad.append(f"{f.name}: a point carries fewer than the three rates "
                       f"(prefill, decode, end to end): {sorted(m)}")
        rows.append({"backend": be, "context": run.get("context_keys"),
                     "batch": run.get("batch_size"), "file": f.name,
                     "rates": rates, "measured_keys": sorted(m)})
    else:
        note = d.get("failure", {}).get("type") or d.get("backend", {}).get("reason")
        print(f"{f.name}: no number ({note})")
seen = {(r["backend"], r["context"], r["batch"]) for r in rows}
for c in contexts:
    for b in batches:
        if ("hf", c, b) not in seen:
            bad.append(f"hf did not measure context {c} at batch {b}")
for r in sorted(rows, key=lambda r: (r["backend"], r["context"] or 0, r["batch"] or 0)):
    print(f"{r['backend']:<6s} C={r['context']:<6} batch={r['batch']:<4} "
          f"prefill={r['rates']['prefill']} decode={r['rates']['decode']} "
          f"end_to_end={r['rates']['end_to_end']} positions/s  [{r['file']}]")
refused = (out / "refused.txt").read_text().split("\n") if (out / "refused.txt").exists() else []
refused = [x for x in refused if x]
if refused:
    print(f"refused: {refused}")
if bad:
    sys.exit("; ".join(bad))
print(f"{len(rows)} measured points across {len({r['backend'] for r in rows})} backend(s)")
PY
st "done"
JOBEOF
drv_start "$JOB"
rm -f "$JOB"
