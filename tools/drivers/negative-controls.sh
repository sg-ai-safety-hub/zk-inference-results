#!/bin/sh
# negative-controls: the whole control suite, on one real segment and on the
# three synthetic shapes, on the sound build.
#
#   tools/drivers/negative-controls.sh <host> <prover-commit> <harness-commit>
#
# `zk-prover compose-probes` proves the honest statement once and then, for
# each control, rebuilds the segment with one value bent and asks the verifier
# to check the result against the honest statement.  A control passes only as a
# designed rejection: the JSON says `accepts: false`, and `falsified` names the
# verdict fields the bend turned off, which is what says the control hit the
# binding it was written for and not something else.  A crash is never a pass.
#
# The real segment is layer 16 of the last token block of `headline-c4096`'s
# plan, proved from that plan's own line so the statement under test is the one
# the headline run proved.  The three synthetic shapes are the ones
# `zk-prover`'s digest gate names.
#
# The suite runs on the SIMD backend.  A control is about the statement, which
# is the same on both backends, and `synthetic-digests` and `reference-digest`
# have already recorded that the CUDA backend reproduces the SIMD proof byte
# for byte on these shapes; the controls rebuild segments at shapes no kernel
# store was emitted for, and evaluating those on the host is what the SIMD
# backend does by construction rather than by a silent fallback.
#
# A target's exit code is recorded beside its output, so a control run that
# dies is visible as a crash and not as a missing file.  The gate fails on a
# crash, on any control the verifier accepted, and on the absence of a control
# over the model tree.  A control the shape cannot state is not a failure: the
# prover skips it by name with its reason, and the run's record carries both.
#
# The seam between the attention output and the o matmul is the one control
# known to crash on a real dump rather than reject (zk-prover #24), and it is
# late in the list, so a crash there would take the whole suite's record with
# it.  It therefore also runs on its own, in a process of its own, through
# `--probe`: whatever the whole suite does, that one control has a record.
#
# The first call pushes zk-prover at the two commits to the host, starts the
# job detached and prints the poll command.  Every later call with the same
# arguments prints the status; once the status says done it fetches the
# outputs into runs/<run-id>/, writes manifest.json from the prover's
# provenance block, and runs check.py.  Nothing measured is typed in here.
#
# Host time, from the run this driver recorded: see REPRODUCE.md.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=negative-controls
. "$HERE/lib/driver.sh"

# ---- the configuration: here and in the manifest, nowhere else ---------------
SPEC=y-delay-vw12
CTX=4096; S=512
SAMPLE_BLOCK=8; SAMPLE_LAYER=16
SHARED="--round even --numbits 9 --z-hi-bits 7 --variants intexp --head-groups 16,8,8 --tight-table"
GKR5="--gkr-key-tiles --gkr-dequant --gkr-residual-stream --gkr-freivalds --gkr-attnout"
# The synthetic shapes, as `zk-prover`'s recorded digests name them.
SYN="--round away --variants intsplit6 --table-bits 16 --s 32 --ctx 128 --hd 32"
RESIDUAL_STREAM="--nout 64 --residual-stream-a 32 --kmax 16 --synth-residual-stream"
SHAPES="syn_sound|--head-groups 2,1 $RESIDUAL_STREAM --diagonal-block
syn_gkrfive|--head-groups 2,1 $RESIDUAL_STREAM --diagonal-block $GKR5
syn_aligned|--head-groups 2,2 --nin 128 --nout 128 --residual-stream-a 32 --kmax 16 --synth-residual-stream --diagonal-block"

drv_finish "$(drv_status)"

# ---- start: push the pinned sources, then the job ----------------------------
drv_check_commits
BUILD=$(drv_build_root)
drv_push "$BUILD/src" "$PROVER"
drv_push "$BUILD/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
SRC=\$B/src; HSRC=\$B/harness-src/harness
OUT=\$R/out
WIT=\$HOME/witness/$(printf '%.12s' "$HARNESS")/$SPEC-c$CTX
mkdir -p \$OUT
$(drv_job_preamble)
export RAYON_NUM_THREADS=\${RAYON_NUM_THREADS:-20}
PY="uv run --project \$HSRC \$UVG python"

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"

[ -f \$WIT/shapes_all.json ] || { st "no witnesses at \$WIT: run headline-c4096 on this host first"; exit 5; }

st "build: simd"
( cd \$SRC && CARGO_TARGET_DIR=\$B/t-simd cargo build --release --locked )
SIMD=\$B/t-simd/release/zk-prover
( cd \$HSRC && uv sync --frozen \$UVG )
cp \$WIT/shapes_all.json \$OUT/shapes.json
PINS=\$(python3 - \$WIT/shapes_all.json <<'PY'
import json, sys
w = json.load(open(sys.argv[1]))["worst"]
print(f"--kmax {w['kmax']} --ao-rem-bits {w['ao_rem_bits']} --fold-rem-bits {w['fold_rem_bits']} --fold-alpha {w['fold_alpha']}")
PY
)

# The real segment's own plan line, taken from the plan headline-c4096 wrote
# rather than written again here.  The line goes LAST on the command line: a
# repeated flag resolves to its last occurrence since zk-prover #92, and the
# line's own pins are the ones the headline run proved this segment under, so
# they have to be the ones that win.  It went first while the first occurrence
# won (zk-prover #30), and either way the rule is the same: the shared prefix is
# the default and the line decides.
( cd \$HSRC && \$PY -m harness.witness.plan --dir \$WIT --blocks $((CTX / S + 1)) --with-block-0 \
    --layers 0-31 --layer-flags="--round even --diagonal-block $GKR5" --out \$R/plan.txt )
LINE=\$(grep -- '--ser-tag B${SAMPLE_BLOCK}L${SAMPLE_LAYER}\$' \$R/plan.txt | sed 's/--ser-tag [A-Za-z0-9_]*//')
[ -n "\$LINE" ] || { st "no plan line for block $SAMPLE_BLOCK layer $SAMPLE_LAYER"; exit 6; }
st "real segment: \$LINE"

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "control",
 "spec": "$SPEC", "context": $CTX, "s": $S,
 "sample_block": $SAMPLE_BLOCK, "sample_layer": $SAMPLE_LAYER,
 "backend": "simd", "shared_flags": "$SHARED", "pins": "\$PINS",
 "real_line": "\$LINE",
 "synthetic_flags": "$SYN",
 "note": "the control suite on one real segment of headline-c4096's plan and on the three synthetic shapes"}
CFG

# ---- the suite, once per target.  A target that dies records its exit code
#      and its last stderr lines; nothing here treats a non-zero exit as a
#      rejection, which is the whole point of recording both.
run_target() {
  name=\$1; shift
  if [ -s \$OUT/\$name.json ] && [ -f \$OUT/\$name.rc ]; then st "\$name already run"; return 0; fi
  st "probes: \$name"
  rc=0
  \$SIMD compose-probes "\$@" > \$OUT/\$name.json 2> \$R/\$name.err || rc=\$?
  echo \$rc > \$OUT/\$name.rc
  tail -40 \$R/\$name.err > \$OUT/\$name.stderr_tail.txt
  st "\$name exit=\$rc"
}

# shellcheck disable=SC2086
run_target real $SHARED \$PINS \$LINE
# zk-prover #24: the o seam's control on its own, so it has a record whatever
# the whole suite above does with it.
# shellcheck disable=SC2086
run_target real_o_seam $SHARED \$PINS \$LINE --probe 'o seam'
printf '%s\n' "$SHAPES" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  # shellcheck disable=SC2086
  run_target \$name $SYN \$flags
done

# ---- the gate ---------------------------------------------------------------
python3 - \$OUT <<'PY'
import json, pathlib, sys
out = pathlib.Path(sys.argv[1])
bad, total, crashed = [], 0, []
summary = {}
for rcf in sorted(out.glob("*.rc")):
    name = rcf.name[:-3]
    rc = int(rcf.read_text().strip())
    doc = None
    try:
        doc = json.loads((out / f"{name}.json").read_text())
    except Exception as e:
        doc = None
        bad.append(f"{name}: no readable output ({e})")
    n_reject = 0
    skipped, unselected, model_tree = [], 0, False
    if doc:
        probes = doc["result"]["probes"]
        for p in probes:
            if p.get("probe") == "honest":
                if not p["result"]["accepts"]:
                    bad.append(f"{name}: the honest proof was rejected")
                continue
            why = p.get("skipped")
            if why:
                # a target run through --probe reports every control it did not
                # select; that is the filter, not a control the shape cannot state
                if why == "not selected by --probe":
                    unselected += 1
                else:
                    skipped.append({"probe": p["probe"], "why": why})
                continue
            if p.get("accepted"):
                bad.append(f"{name}: the control {p['probe']!r} was accepted")
                continue
            n_reject += 1
            # The control that says the norm weight is the model's and not the
            # prover's is the one that covers the model tree. Since the
            # preprocessed trace was split in two it rejects through the model
            # root, and compose-probes pins both of the honest run's roots
            # (zk-prover #66), so what identifies it is the refusal it was
            # written for and the root that moved. Its name says norm_scale, so
            # the name is not what this reads.
            if ("model root" in str(p.get("expect_reject_by", "")).lower()
                    and p.get("model_root_differs_from_honest")):
                model_tree = True
    if rc:
        crashed.append(f"{name} (exit {rc})")
    total += n_reject
    summary[name] = {"exit": rc, "designed_rejections": n_reject,
                     "skipped": [s["probe"] for s in skipped],
                     "skipped_why": skipped, "not_selected": unselected,
                     "model_tree_control": model_tree}
    print(f"{name:14s} exit {rc}  designed rejections {n_reject}  "
          f"skipped {len(skipped)}  not selected {unselected}  "
          f"model-tree control {model_tree}")
    for s in skipped:
        print(f"{'':14s}   skipped by name: {s['probe']} -- {s['why']}")
(out / "controls.json").write_text(json.dumps(
    {"targets": summary, "designed_rejections": total, "crashes": len(crashed)}, indent=1) + "\n")
print(f"total: {total} designed rejections, {len(crashed)} crash(es)")
if crashed:
    bad.append("a control run crashed: " + ", ".join(crashed) + " (zk-prover #24, #27)")
if not any(v["model_tree_control"] for v in summary.values()):
    bad.append("no control covers the model tree (zk-prover #17)")
if bad:
    sys.exit("; ".join(bad))
print("every control is a designed rejection; no crash; the model tree is covered")
PY
st "done"
JOBEOF
drv_start "$JOB"
rm -f "$JOB"
