#!/bin/sh
# The job script a perplexity campaign runs on the host: fetch the weights if
# the host does not have them, measure one perplexity per quantization variant
# over the fixed corpus, measure the cosine similarity of the logits against
# fp32 where the campaign asks for it, and gate the result.  Sourced by a
# driver, never run.
#
#     drv_quality_job > "$JOB"
#
# The driver decides everything the job measures and sets it in variables
# first; this file names no model and no variant of its own.  Two campaigns
# therefore differ in their driver and nowhere else, which is the point: what
# is under test must be the only difference between them.
#
# Variables the driver sets: NAME BUILD MODEL DEVICE CHUNKS XTHREADS SPECS
# REQUIRED COSINE_SPECS LABEL.
#
# `REQUIRED` is the variants the campaign cannot do without; `SPECS` may name
# more.  A variant outside `REQUIRED` that does not measure is recorded in
# `out/refused.txt` and the run goes on, because one variant that a model's
# architecture cannot take should not cost the campaign the rows that it can.
#
# This is a harness run.  Nothing in it proves anything, so its outputs carry
# no binding table and no proof digest, and `lib/manifest.py` records it with
# `kind` `harness` and no prover commit (zk-results issue #51).  No prover is
# built, pushed or run.
#
# The harness writes its calibration files and its token cache into a working
# directory beside the run's outputs and not into them: those are inputs, they
# are specific to the model, and a run directory holds outputs.

drv_quality_job() {
cat <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
HSRC=\$B/harness-src/harness
OUT=\$R/out
WORK=\$R/work            # the harness's own output directory, one per model
mkdir -p \$OUT \$WORK
$(drv_job_preamble)
export ZK_MODEL=$MODEL ZK_DEVICE=$DEVICE ZK_THREADS=$XTHREADS ZK_OUT=\$WORK
# The default torch is the CPU build, which is what a CPU campaign wants, so no
# call here selects the harness's cuda group.  A run before or after this one
# that does select it syncs the environment back the other way; the lockfile
# pins both builds, so neither sync resolves anything.
PY="uv run --project \$HSRC python"

st "cores: \$(nproc), threads $XTHREADS, device $DEVICE"
st "harness: \$(cat \$B/harness-src/.source-commit)"

# 1. the harness at its pinned commit
( cd \$HSRC && uv sync --frozen )

# 2. the weights, if this host does not already hold them.  The size and the
#    time are measured here rather than assumed, and go into the run's own
#    configuration record.
WEIGHTS=\$( cd \$HSRC && \$PY - <<'PY'
import json, os, time
t0 = time.time()
from huggingface_hub import snapshot_download
p = snapshot_download(os.environ["ZK_MODEL"])
# every file in a snapshot is a link to the blob that holds it, one to one,
# and getsize follows the link, so this is the size on disk and counts nothing
# twice
n = sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(p) for f in fs)
print(json.dumps({"bytes": n, "seconds": round(time.time() - t0, 1)}))
PY
)
st "weights: \$WEIGHTS"

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "$LABEL", "kind": "harness",
 "model": "$MODEL", "device": "$DEVICE", "threads": $XTHREADS,
 "chunks": $CHUNKS, "positions": $((CHUNKS * 512)),
 "specs": "$SPECS", "required": "$REQUIRED", "cosine_specs": "$COSINE_SPECS",
 "weights": \$WEIGHTS,
 "corpus": "harness/witness/text.txt, the fixed corpus; every output names it by digest"}
CFG

# 3. one perplexity per variant, one process each so peak memory stays at one
#    model.  A variant already in ppl.json is not measured again, so a job that
#    was interrupted is restarted for the price of what it did not finish.
have() {   # have <file> <key>
  python3 - "\$1" "\$2" <<'PY'
import json, os, sys
f, k = sys.argv[1], sys.argv[2]
if not os.path.exists(f):
    raise SystemExit(1)
d = json.load(open(f))
d = d["result"] if "provenance" in d and "result" in d else d
raise SystemExit(0 if k in d else 1)
PY
}
for s in $SPECS; do
  if have \$WORK/ppl.json "\$s"; then st "ppl \$s: already measured"; continue; fi
  st "ppl: \$s"
  T0=\$(date +%s)
  if ( cd \$HSRC && \$PY -m harness.witness.ppl --spec \$s --chunks $CHUNKS ); then
    st "ppl \$s: done in \$(( \$(date +%s) - T0 ))s"
  else
    printf 'ppl %s\n' "\$s" >> \$OUT/refused.txt
    st "ppl \$s: did not measure; recorded in out/refused.txt"
  fi
done
( cd \$HSRC && \$PY -m harness.witness.ppl --report ) || true

# 4. the cosine similarity of the logits against fp32, where the campaign asks
#    for it: the statistic a published comparison reports, which a perplexity
#    does not give.
for s in $COSINE_SPECS; do
  if have \$WORK/cosine.json "\$s"; then st "cosine \$s: already measured"; continue; fi
  st "cosine: \$s"
  T0=\$(date +%s)
  if ( cd \$HSRC && \$PY -m harness.witness.cosine --spec \$s --chunks $CHUNKS ); then
    st "cosine \$s: done in \$(( \$(date +%s) - T0 ))s"
  else
    printf 'cosine %s\n' "\$s" >> \$OUT/refused.txt
    st "cosine \$s: did not measure; recorded in out/refused.txt"
  fi
done

# 5. what the run delivers: the rows, and the per-token losses they came from.
cp \$WORK/ppl.json \$OUT/ppl.json
[ ! -f \$WORK/cosine.json ] || cp \$WORK/cosine.json \$OUT/cosine.json
rm -rf \$OUT/nll; cp -r \$WORK/nll \$OUT/nll
du -sh \$OUT | awk '{print "fetched size: " \$1 "  " \$2}'

# 6. the gate: every variant the campaign cannot do without is measured, every
#    output says where it came from, and the paired differences are in the file
#    the harness wrote them into.
python3 - \$OUT "$SPECS" "$REQUIRED" "$COSINE_SPECS" <<'PY'
import json, pathlib, sys
out, specs, required, cos = (pathlib.Path(sys.argv[1]), sys.argv[2].split(),
                             sys.argv[3].split(), sys.argv[4].split())
cfg = json.loads((out / "config.json").read_text())
doc = json.loads((out / "ppl.json").read_text())
bad = []
if "provenance" not in doc or "result" not in doc:
    sys.exit("ppl.json carries no provenance block; this harness commit writes none")
p, rows = doc["provenance"], doc["result"]
print(f"harness {p['commit']} dirty={p['dirty']}  model {p['model']} "
      f"revision {p['model_revision']}  device {p['device']}  torch {p['versions']['torch']}")
print(f"corpus {p['corpus']['file']} {p['corpus']['sha256'][:16]} {p['corpus']['bytes']} bytes")
print(f"weights {cfg['weights']['bytes']:,} bytes in {cfg['weights']['seconds']} s")
missing = [s for s in required if s not in rows]
if missing:
    bad.append(f"required variants not measured: {missing}")
base = rows.get("fp32", {}).get("ppl")
if base is None:
    bad.append("fp32 was not measured; nothing can be compared against it")
for s in specs:
    if s not in rows:
        print(f"{s:<22} not measured")
        continue
    r = rows[s]
    d = "--" if s == "fp32" or base is None else f"{(r['ppl'] / base - 1) * 100:+.3f}%"
    print(f"{s:<22} ppl {r['ppl']:9.4f}  vs fp32 {d:>9}  "
          f"{r['tokens']} positions, {r['seconds']} s")
    if r["chunks"] != cfg["chunks"]:
        bad.append(f"{s}: {r['chunks']} chunks, not the {cfg['chunks']} configured")
# The paired difference against fp32 is worked out by the harness from the
# per-token losses and written beside the rows; read back, not recomputed, so
# there is one place it is worked out.
pairs = doc.get("paired", {})
if not pairs and len(rows) > 1:
    bad.append("ppl.json carries no paired table; the harness writes one from the "
               "per-token losses whenever fp32 is among them")
for s in specs:
    if s in pairs:
        q = pairs[s]
        print(f"{s:<22} vs fp32 {q['delta_pct']:+.4f}%  paired standard error "
              f"{q['se_nats']:.6f} nats over {q['positions']} positions")
if cos:
    f = out / "cosine.json"
    if not f.exists():
        bad.append("no cosine.json, and the campaign asked for one")
    else:
        cdoc = json.loads(f.read_text())
        crows = cdoc["result"] if "provenance" in cdoc else cdoc
        for s in cos:
            if s not in crows:
                print(f"{s:<22} cosine not measured")
                continue
            c = crows[s]
            print(f"{s:<22} cosine {c['cosine_mean']:.6f} +/- {c['cosine_se']:.6f} "
                  f"(min {c['cosine_min']:.6f})")
refused = (out / "refused.txt").read_text().split("\n") if (out / "refused.txt").exists() else []
refused = [r for r in refused if r]
if refused:
    print(f"{len(refused)} measurements refused: {refused}")
if bad:
    sys.exit("; ".join(bad))
print(f"{len(rows)} variants measured; every one the campaign requires is present")
PY
st "done"
JOBEOF
}
