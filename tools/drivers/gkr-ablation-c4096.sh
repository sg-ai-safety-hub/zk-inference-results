#!/bin/sh
# gkr-ablation-c4096: each GKR reduction alone, on one sample of segments.
#
#   tools/drivers/gkr-ablation-c4096.sh <host> <prover-commit> <harness-commit>
#
# Seven configurations of the same 32 segments: none of the five reductions,
# the key tiles' reduction alone, each of the other four on top of it, and all
# five together.  Four of the five are not configurations on their own -- they
# join the key tiles' backend rather than standing up one of their own, and the
# prover refuses them without it -- so what one of them costs is what it costs
# on top of the key tiles.  The segments are the 32
# layers of the last token block of `headline-c4096`'s plan -- the block with
# the longest prefix, so the reductions are priced where they weigh most -- and
# they are proved from the same witnesses, under the same shared pins, with the
# same binding gadgets and with no skip flag.  A reduction changes the proof
# and not the statement, so the seven runs are seven prices for one statement.
#
# Every run here is a control except the one with all five on, which is the
# paper's configuration on a sample and not the headline row: the headline is
# the whole sequence, `headline-c4096`.
#
# The witnesses are the ones `headline-c4096` extracted; this driver refuses to
# run without them rather than extracting a second set, because a comparison
# across configurations is only a comparison if the witnesses are the same.
# The prover build and the kernel store are shared too: the seven
# configurations' shapes are emitted into the one store and the CUDA backend is
# rebuilt once.
#
# The first call pushes zk-prover at the two commits to the host, starts the
# job detached and prints the poll command.  Every later call with the same
# arguments prints the status; once the status says done it fetches the
# outputs into runs/<run-id>/, writes manifest.json from the prover's
# provenance block, and runs check.py.  Nothing measured is typed in here.
#
# Host time, from the run this driver recorded: see REPRODUCE.md.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=gkr-ablation-c4096
. "$HERE/lib/driver.sh"

# ---- the configuration: here and in the manifest, nowhere else ---------------
MODEL=${ZK_MODEL:-unsloth/Llama-3.1-8B-Instruct}
SPEC=y-delay-vw12
HEAD_SPEC=b10-final
CTX=4096; S=512
NBLOCK=$(( (CTX + S) / S ))
NLAY=32
SAMPLE=8                   # the plan's last token block: 32 segments at prefix c = $CTX
SHARED="--round even --numbits 9 --z-hi-bits 7 --variants intexp --head-groups 16,8,8 --tight-table"
BASE="--round even --diagonal-block"   # every binding gadget is on by default; no skip flag anywhere
GKR5="--gkr-key-tiles --gkr-dequant --gkr-residual-stream --gkr-freivalds --gkr-attnout"
# One line per configuration: <name>|<the --gkr-* flags after $BASE>.
#
# Four of the five reductions are not configurations on their own: the
# dequantization gadgets, the residual stream, the Freivalds checks and the
# attention output all join the key tiles' own LogUp-GKR backend rather than
# standing up one of their own, and the prover refuses each of them without
# `--gkr-key-tiles` ("it composes with --gkr-key-tiles; it does not replace it").  So
# what one of them costs is what it costs *on top of the key tiles*, and that is
# the pair each line below makes with `bands`.
CONFIGS="none|
bands|--gkr-key-tiles
bands_dequant|--gkr-key-tiles --gkr-dequant
bands_residual_stream|--gkr-key-tiles --gkr-residual-stream
bands_freivalds|--gkr-key-tiles --gkr-freivalds
bands_attnout|--gkr-key-tiles --gkr-attnout
all_five|$GKR5"
PIPELINE=1                 # ZK_PIPELINE: generate segment k+1 while proving segment k
KERNEL_FAMILIES=zk_chan_eval,zk_key_eval,zk_row_eval,zk_attn_out_eval,zk_dequant_eval,zk_freivalds_eval,zk_exp_table_eval,zk_table_eval,zk_residual_stream_eval,zk_residual_stream_table_eval

drv_finish "$(drv_status)"

# ---- start: push the pinned sources, then the job ----------------------------
drv_check_commits
BUILD=$(drv_build_root)
drv_push "$BUILD/src" "$PROVER"
drv_push "$BUILD/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
SRC=\$B/src; HSRC=\$B/harness-src/harness; GEN=\$B/gen
OUT=\$R/out
WIT=\$HOME/witness/$(printf '%.12s' "$HARNESS")/$SPEC-c$CTX
mkdir -p \$OUT \$GEN
$(drv_job_preamble)
export RAYON_NUM_THREADS=\${RAYON_NUM_THREADS:-16} ZK_KERNEL_STORE=\$GEN
PY="uv run --project \$HSRC \$UVG python"

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "ablation",
 "model": "$MODEL", "spec": "$SPEC", "head_spec": "$HEAD_SPEC",
 "context": $CTX, "s": $S, "blocks": $NBLOCK, "layers": $NLAY,
 "sample_block": $SAMPLE, "sample_segments": $NLAY, "pipeline": $PIPELINE,
 "shared_flags": "$SHARED", "base_layer_flags": "$BASE",
 "configurations": {"none": "", "bands": "--gkr-key-tiles",
   "bands_dequant": "--gkr-key-tiles --gkr-dequant",
   "bands_residual_stream": "--gkr-key-tiles --gkr-residual-stream",
   "bands_freivalds": "--gkr-key-tiles --gkr-freivalds",
   "bands_attnout": "--gkr-key-tiles --gkr-attnout", "all_five": "$GKR5"},
 "note": "the 32 layer segments of token block $SAMPLE, proved seven times; the witnesses are headline-c4096's"}
CFG

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
st "nvcc: \$(nvcc --version | tail -2 | head -1)"

[ -f \$WIT/shapes_all.json ] || { st "no witnesses at \$WIT: run headline-c4096 on this host first"; exit 5; }

st "build"
( cd \$SRC && CARGO_TARGET_DIR=\$B/t-simd cargo build --release --locked )
SIMD=\$B/t-simd/release/zk-prover
( cd \$HSRC && uv sync --frozen \$UVG )
cp \$WIT/shapes_all.json \$OUT/shapes.json
PINS=\$(python3 - \$WIT/shapes_all.json <<'PY'
import json, sys
w = json.load(open(sys.argv[1]))["worst"]
print(f"--kmax {w['kmax']} --ao-rem-bits {w['ao_rem_bits']} --fold-rem-bits {w['fold_rem_bits']} --fold-alpha {w['fold_alpha']}")
PY
)
st "pins: \$PINS"

# 1. one plan per configuration, and the sample of it this run proves.  The
#    plan is written over the whole sequence so a line is the line the headline
#    plan carries, and then the sample block's lines are taken out of it.
printf '%s\n' "$CONFIGS" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  ( cd \$HSRC && \$PY -m harness.witness.plan --dir \$WIT --blocks $NBLOCK --with-block-0 \
      --layers 0-$((NLAY - 1)) --layer-flags="$BASE \$flags" --out \$R/\$name.full.txt )
  grep -- '--ser-tag B${SAMPLE}L' \$R/\$name.full.txt > \$OUT/\$name.plan.txt
  n=\$(grep -cv '^#' \$OUT/\$name.plan.txt)
  [ "\$n" = "$NLAY" ] || { st "\$name: the sample has \$n lines, not $NLAY"; exit 6; }
  # the distinct kernel shapes among them: within one block the prefix is one
  # value, so the master table width and the line's flags are the whole key
  awk '{tb=""; for (i = 1; i < NF; i++) if (\$i == "--table-bits") tb = \$(i + 1);
        if (!(tb in seen)) { seen[tb] = 1; print }}' \$OUT/\$name.plan.txt > \$R/\$name.emit.txt
  st "\$name: \$n segments, \$(wc -l < \$R/\$name.emit.txt) kernel shapes"
done

# 2. the device kernels for every shape of every configuration, into the one
#    store, installed once and compiled into the CUDA backend once
K=\$SRC/prover/kernels
[ -d \$K ] || { st "no prover/kernels in this prover commit; the CUDA backend would evaluate constraints on the CPU"; exit 3; }
if [ ! -f \$R/kernels.done ]; then
  printf '%s\n' "$CONFIGS" | while IFS='|' read -r name flags; do
    [ -n "\$name" ] || continue
    st "emit: \$name"
    while read -r line; do
      case "\$line" in '#'*|'') continue ;; esac
      args=\$(printf '%s\n' "\$line" | sed 's/--ser-tag [A-Za-z0-9_]*//')
      # zk-prover #57: an emitter's placeholder claims can be one entry short on
      # a segment that carries the embedding gadget.  A kernel is looked up by
      # fingerprint and the sample's shapes share theirs, so a refused lowering
      # costs either nothing or an announced kernel fallback line, and the gate
      # below fails the run on any such line.
      for emit in cudaemit genemit; do
        case \$emit in
          cudaemit) opts="--block 256 --min-blocks 2" ;;
          genemit)  opts="--families $KERNEL_FAMILIES" ;;
        esac
        if ! \$SIMD \$emit $SHARED \$PINS \$args \$opts --out \$GEN > /dev/null; then
          printf '%s %s\n' "\$name" "\$line" >> \$OUT/\$emit-refused.txt
          st "\$emit refused a shape of \$name (zk-prover #57)"
        fi
      done
    done < \$R/\$name.emit.txt
  done
  python3 \$K/m2b_kernels.py --fork \$SRC/nitroo --gen \$GEN
  python3 \$K/m4b_kernels.py --fork \$SRC/nitroo --gen \$GEN --src \$K
  find \$SRC/nitroo/crates/stwo/src/stwo_cuda/cuda \( -name '*.cu' -o -name '*.cuh' \) -exec touch {} +
  cp \$GEN/cudakernels.rs \$GEN/gencudakernels.rs \$SRC/prover/src/
  grep -q ' dirty\$' \$SRC/.source-commit || sed -i 's/\$/ dirty/' \$SRC/.source-commit
  touch \$R/kernels.done
fi
( cd \$SRC && CARGO_TARGET_DIR=\$B/t-cuda cargo build --release --locked -p zk-prover --features cuda )
CUDA=\$B/t-cuda/release/zk-prover
st "kernels installed"

# 3. the seven timed runs, one process each, pipelined, the card sampled once a
#    second.  A configuration whose output is already written is not proved
#    again.  No statement is serialized: the sample is one token block and what
#    this run measures is the price of a reduction, not the chain, which the
#    headline and the control runs check over the whole sequence.
printf '%s\n' "$CONFIGS" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  if [ -s \$OUT/\$name.json ]; then st "\$name already proved"; continue; fi
  rm -f \$R/\$name.mem
  ( while true; do echo "\$(date +%s) \$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits)" >> \$R/\$name.mem; sleep 1; done ) & sampler=\$!
  ZK_PIPELINE=$PIPELINE \$CUDA compose-chunks $SHARED \$PINS --plan \$OUT/\$name.plan.txt \
      > \$OUT/\$name.json 2> \$R/\$name.err || { kill \$sampler; rm -f \$OUT/\$name.json; st "\$name failed, see \$R/\$name.err"; exit 4; }
  kill \$sampler
  grep -c 'kernel fallback:' \$R/\$name.err > \$OUT/\$name.fallbacks || true
  python3 - \$R/\$name.mem \$OUT/\$name.mem.json <<'PY'
import json, sys
v = [int(l.split()[1]) for l in open(sys.argv[1]) if len(l.split()) == 2 and l.split()[1].isdigit()]
json.dump({"samples": len(v), "period_s": 1, "max_mib": max(v, default=0),
           "mean_mib": round(sum(v) / len(v), 1) if v else 0}, open(sys.argv[2], "w"))
PY
  st "\$name done"
done

# 4. the gate: every configuration proved, no skip in effect, every edge bound,
#    no lookup evaluated on the host instead of by its generated kernel
python3 - \$OUT <<'PY'
import json, pathlib, sys
out = pathlib.Path(sys.argv[1])
cfg = json.loads((out / "config.json").read_text())
bad, base = [], None
for name in cfg["configurations"]:
    f = out / f"{name}.json"
    if not f.exists():
        bad.append(f"{name}: no output")
        continue
    doc = json.loads(f.read_text())
    p, s = doc["provenance"], doc["result"]["summary"]
    if name == "none":
        base = s["fresh_sum"]
    share = "" if not base else f", {100 * s['fresh_sum'] / base:.1f}% of the cells with none on"
    print(f"{name:16s} {s['n']} segments, loop {s['loop_secs']:.1f} s, "
          f"fresh {s['fresh_sum']:,.0f} cells{share}, skips {p['unsound_skips'] or 'none'}, "
          f"all_bound {p['binding']['all_bound']}, unbound {p['binding']['unbound']}")
    if p["unsound_skips"]:
        bad.append(f"{name}: unsound skips in effect")
    if not p["binding"]["all_bound"]:
        bad.append(f"{name}: unbound edges {p['binding']['unbound']}")
    k = int((out / f"{name}.fallbacks").read_text().strip())
    if k:
        bad.append(f"{name}: {k} kernel fallback lines")
if bad:
    sys.exit("; ".join(bad))
print("every configuration proved; no skip; every edge bound; no kernel fallback")
PY
st "done"
JOBEOF
drv_start "$JOB"
rm -f "$JOB"
