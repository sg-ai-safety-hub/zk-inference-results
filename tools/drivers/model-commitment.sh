#!/bin/sh
# model-commitment: the model commitment the verifier holds, and every segment
# of the headline sequence checked against it.
#
#   tools/drivers/model-commitment.sh <host> <prover-commit> <harness-commit>
#
# A segment's statement names a model root, and the verifier's own replay only
# says that the proof's second commitment is the one the statement names. Which
# model that root is, is the statement's own assertion and is checked by nothing
# until a published commitment is compared with it. This campaign publishes that
# commitment and makes the comparison over a whole sequence.
#
# `zk-prover model-roots --plan PLAN` derives the table from the model: it runs
# `zk-prover expect-root` once per plan line, in a process of its own, and
# collects one row per (layer, prefix width) carrying that cell's shape root and
# that layer's model root, the model's content hash, and the per-layer
# calibration a verifier needs to derive the shape root itself. It refuses to
# write a manifest whose rows disagree about a layer's model root, because a
# manifest that does commits nothing.
#
# `zk-prover boundary-grid --expect-model-roots` then compares every segment's
# model root against the manifest's row for that segment's layer, and
# `--expect-pre-roots` compares every segment's shape root against the row for
# its cell. Both comparisons also check the model hash the row was derived
# under against the one the statement names, so a manifest published for another
# model is a named failure and not an accident.
#
# The proofs are `headline-c4096`'s, read back off the host as bytes: that run
# keeps its serialized statements and proofs (`KEEP_SER`), and this campaign
# makes no proof of its own. It is therefore a `verifier` run -- it commits
# nothing, so no output carries a binding table -- and `lib/manifest.py` is told
# so on the command line and checks that the run indeed carries no proof.
#
# Two forms of the table are derived and compared. The published one is the
# prover's: every row from the whole dump, which is what a manifest built before
# any segment has been proved has to do. The second is the verifier's
# (`--weights-only --params-dir`): every row from the model half of the dump and
# from the statement the run itself serialized. The two must agree on every
# layer's model root or the commitment is not a function of the model alone.
# The second is derived over the first token block, which is one chunk at every
# one of the 32 layers, because it is a cross-check and not the publication.
#
# The first call pushes zk-prover at the two commits to the host, starts the
# job detached and prints the poll command.  Every later call with the same
# arguments prints the status; once the status says done it fetches the
# outputs into runs/<run-id>/, writes manifest.json from the prover's
# provenance block, and runs check.py.  Nothing measured is typed in here.
#
# Host time, from the run this driver recorded: see REPRODUCE.md.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=model-commitment
. "$HERE/lib/driver.sh"

# ---- the configuration: here and in the manifest, nowhere else ---------------
LABEL=verifier             # this run proves nothing; it checks proofs another run made
DRV_KIND=verifier          # what lib/manifest.py is told, because no output can say it
SEQ=headline-c4096         # the campaign whose plan and proofs are checked
SPEC=y-delay-vw12
CTX=4096; S=512
SHARED="--round even --numbits 9 --z-hi-bits 7 --variants intexp --head-groups 16,8,8 --tight-table"
# The same flags without `--tight-table`, for the verifier's form alone. That
# flag sizes the exp table off the witness's own shifts and the model-only load
# has no witness to read them from, so the prover refuses the pair and says the
# width comes from the statement's `log_table` there instead. The exp table is a
# shape column and no part of the model tree -- `model-roots` says so itself
# where a layer's blocks carry two widths -- so dropping it moves no model root,
# which is the only thing the two derivations are compared on.
SHARED_WEIGHTS=$(printf '%s' "$SHARED" | sed 's/ --tight-table//')
# The verifier's form is a cross-check over one token block: `model-roots` keeps
# one row per (layer, prefix width) and the first block is one chunk at each of
# the 32 layers, so the block covers every layer's model root exactly once.
VERIFIER_LIMIT=32

drv_finish "$(drv_status)"

# ---- start: push the pinned sources, then the job ----------------------------
drv_check_commits
BUILD=$(drv_build_root)
drv_push "$BUILD/src" "$PROVER"
drv_push "$BUILD/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
SRC=\$B/src; HSRC=\$B/harness-src/harness
OUT=\$R/out
SEQR=\$HOME/runs/$SEQ
PLAN=\$SEQR/out/plan.txt; SER=\$SEQR/ser
WIT=\$HOME/witness/$(printf '%.12s' "$HARNESS")/$SPEC-c$CTX
mkdir -p \$OUT
$(drv_job_preamble)
export RAYON_NUM_THREADS=\${RAYON_NUM_THREADS:-20}

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
[ -f \$PLAN ] || { st "no plan at \$PLAN: run $SEQ on this host first"; exit 5; }
[ -d \$SER ] || { st "no serialized statements and proofs at \$SER: run $SEQ with KEEP_SER=1"; exit 5; }
[ -f \$WIT/shapes_all.json ] || { st "no witnesses at \$WIT: run $SEQ on this host first"; exit 5; }

st "build: simd"
( cd \$SRC && CARGO_TARGET_DIR=\$B/t-simd cargo build --release --locked )
SIMD=\$B/t-simd/release/zk-prover

PINS=\$(python3 - \$WIT/shapes_all.json <<'PINPY'
import json, sys
w = json.load(open(sys.argv[1]))["worst"]
print(f"--kmax {w['kmax']} --ao-rem-bits {w['ao_rem_bits']} --fold-rem-bits {w['fold_rem_bits']} --fold-alpha {w['fold_alpha']}")
PINPY
)
st "pins: \$PINS"
N=\$(grep -cv '^#' \$PLAN)
NSER=\$(find \$SER -type f | wc -l)
st "plan: \$N segments; serialized files: \$NSER"

# The link counts are the sequence run's own, read off the run it checks rather
# than restated here: a grid told a different number would be a different grid.
LL=\$(python3 -c "import json,sys;print(json.load(open(sys.argv[1]))['expect_layer_links'])" \$SEQR/out/config.json)
TL=\$(python3 -c "import json,sys;print(json.load(open(sys.argv[1]))['expect_token_links'])" \$SEQR/out/config.json)

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "$LABEL",
 "sequence_run": "$SEQ", "spec": "$SPEC", "context": $CTX, "s": $S,
 "segments": \$N, "serialized_files": \$NSER,
 "shared_flags": "$SHARED", "pins": "\$PINS",
 "expect_layer_links": \$LL, "expect_token_links": \$TL,
 "verifier_form_limit": $VERIFIER_LIMIT,
 "note": "the published model commitment, derived from the model over the plan $SEQ proved, and every one of that run's segments checked against it"}
CFG

# 1. the published commitment: one row per (layer, prefix width), derived from
#    the model the plan names.  This is the manifest the verifier holds.
if [ ! -s \$OUT/model-roots.json ]; then
  T0=\$(date +%s)
  \$SIMD model-roots --plan \$PLAN --pins "$SHARED \$PINS" --out \$OUT/model-roots.json \
      > \$OUT/model_roots.json 2> \$R/model_roots.err
  echo \$((\$(date +%s) - T0)) > \$R/model_roots.secs
fi
st "commitment derived in \$(cat \$R/model_roots.secs 2>/dev/null || echo '?')s"

# 2. the verifier's form of the same derivation, over one token block: from the
#    model half of the dump and the statement this sequence serialized.
if [ ! -s \$OUT/model-roots-verifier.json ]; then
  T0=\$(date +%s)
  \$SIMD model-roots --plan \$PLAN --pins "$SHARED_WEIGHTS \$PINS" --weights-only --params-dir \$SER \
      --limit $VERIFIER_LIMIT --out \$OUT/model-roots-verifier.json \
      > \$OUT/model_roots_verifier.json 2> \$R/model_roots_verifier.err
  echo \$((\$(date +%s) - T0)) > \$R/model_roots_verifier.secs
fi
st "verifier form derived in \$(cat \$R/model_roots_verifier.secs 2>/dev/null || echo '?')s"

# 3. the commitment itself: the per-layer table and its digest, which is what a
#    paper cites.  The digest is over a canonical rendering of the layer number,
#    the model root and the model hash and nothing else, so it moves when the
#    commitment moves and not when the file is reformatted.
python3 - \$OUT/model-roots.json \$OUT/model-roots-verifier.json \$OUT/commitment.json <<'CMTPY'
import hashlib, json, sys
rows = json.load(open(sys.argv[1]))
ver = json.load(open(sys.argv[2]))
by_layer = {}
for r in rows:
    layer, root, model = r["layer"], r["model_root"], r["model"]
    prev = by_layer.setdefault(layer, {"layer": layer, "model_root": root, "model": model,
                                       "cells": 0})
    assert prev["model_root"] == root, f"layer {layer} carries two model roots"
    assert prev["model"] == model, f"layer {layer} names two models"
    prev["cells"] += 1
table = [by_layer[k] for k in sorted(by_layer)]
canon = "\n".join(f"{r['layer']} {r['model_root']} {r['model']}" for r in table) + "\n"
digest = hashlib.sha256(canon.encode()).hexdigest()
# the verifier's form, layer by layer, against the published one
disagree = []
for r in ver:
    want = by_layer.get(r["layer"])
    if want is None:
        disagree.append({"layer": r["layer"], "why": "the published commitment has no row"})
    elif want["model_root"] != r["model_root"]:
        disagree.append({"layer": r["layer"], "published": want["model_root"],
                         "verifier_form": r["model_root"]})
    elif want["model"] != r["model"]:
        disagree.append({"layer": r["layer"], "published_model": want["model"],
                         "verifier_form_model": r["model"]})
json.dump({"layers": len(table), "cells": len(rows), "sha256": digest,
           "canonical": canon, "table": table,
           "verifier_form_layers": len({r["layer"] for r in ver}),
           "verifier_form_disagreements": disagree},
          open(sys.argv[3], "w"), indent=1)
print(f"commitment: {len(table)} layer coordinates over {len(rows)} cells, sha256 {digest}")
print(f"verifier form: {len({r['layer'] for r in ver})} layers, "
      f"{len(disagree)} disagreement(s)")
CMTPY

# 4. every segment's model root and shape root against the manifest, over the
#    serialized statements and proofs of the sequence run and nothing else.
#
#    `--prompt` is the sequence run's own published ids, and it is not optional
#    here.  A grid told nothing about the prompt has no way to know which
#    positions were given and which the model wrote, so it reads every position
#    after a head block's first as generated and asks that each equal the argmax
#    proved for the one before it -- which is false for a prompt position, and
#    is what a grid run without it reports.  The sequence run wrote the file
#    beside its outputs and this reads it from there rather than making it
#    again.
PROMPT=\$SEQR/prompt_ids.json
[ -f \$PROMPT ] || { st "no published prompt ids at \$PROMPT: run $SEQ on this host first"; exit 5; }
GRIDARGS="--expect-layer-links \$LL --expect-token-links \$TL --expect-model-roots --expect-pre-roots --verify --prompt"
GRIDSUM=\$(printf '%s' "\$GRIDARGS" | sha256sum | cut -c1-16)
if [ "\$(cat \$R/grid.done 2>/dev/null)" != "\$GRIDSUM" ]; then
  T0=\$(date +%s)
  \$SIMD boundary-grid --dir \$SER --plan \$PLAN \
      --expect-layer-links \$LL --expect-token-links \$TL \
      --expect-model-roots \$OUT/model-roots.json --expect-pre-roots \$OUT/model-roots.json \
      --verify --prompt \$PROMPT \
      > \$OUT/grid.json 2> \$R/grid.err
  echo \$((\$(date +%s) - T0)) > \$R/grid.secs
  printf '%s\n' "\$GRIDSUM" > \$R/grid.done
fi
st "grid checked in \$(cat \$R/grid.secs 2>/dev/null || echo '?')s"

python3 - \$OUT \$R <<'TIMEPY'
import json, os, sys
out, r = sys.argv[1], sys.argv[2]
def secs(name):
    p = os.path.join(r, f"{name}.secs")
    return int(open(p).read().strip()) if os.path.exists(p) else None
json.dump({"model_roots_seconds": secs("model_roots"),
           "model_roots_verifier_seconds": secs("model_roots_verifier"),
           "grid_seconds": secs("grid"),
           "note": "wall-clock seconds of the three steps; this run proves nothing, so "
                   "none of the four proving timing scopes applies to it"},
          open(os.path.join(out, "timing.json"), "w"), indent=1)
TIMEPY

# 5. the gate: the manifest covers every layer the grid uses, every segment's
#    model root is the manifest's, every segment's shape root is the manifest's,
#    the two derivations agree, and the sequence still chains.
python3 - \$OUT <<'GATEPY'
import json, pathlib, sys
out = pathlib.Path(sys.argv[1])
bad = []
c = json.loads((out / "commitment.json").read_text())
g = json.loads((out / "grid.json").read_text())["result"]
mr = json.loads((out / "model_roots.json").read_text())["result"]
print(f"commitment: {c['layers']} layer coordinates, {c['cells']} cells, "
      f"sha256 {c['sha256']}")
print(f"model-roots: {mr['distinct_cells']} distinct cells, {mr['layers']} layers, "
      f"{mr['models']} model(s), {len(mr['rejections'])} rejection(s)")
if mr["rejections"]:
    bad.append(f"model-roots rejected {len(mr['rejections'])} layer(s): {mr['rejections']}")
if c["verifier_form_disagreements"]:
    bad.append("the verifier's form of the derivation disagrees with the published "
               f"commitment: {c['verifier_form_disagreements']}")
if c["verifier_form_layers"] != c["layers"] - 1 and c["verifier_form_layers"] != c["layers"]:
    print(f"note: the verifier form covered {c['verifier_form_layers']} of "
          f"{c['layers']} layer coordinates")
model = g["model_roots"]["chunks"]
pre = g["pre_roots"]["chunks"]
n_bad_model = sum(1 for x in model if not x["ok"] or not x["model_ok"])
n_bad_pre = sum(1 for x in pre if not x["ok"] or not x["model_ok"])
print(f"grid: {len(model)} segments' model roots compared, {n_bad_model} not the manifest's; "
      f"{len(pre)} shape roots compared, {n_bad_pre} not the manifest's")
print(f"grid: {g['links_passed']}/{g['links_run']} of {g['links_expected']} implied links "
      f"passed; models named {g['models']['distinct']}; all_chain {g['all_chain']}")
v, tk = g.get("verified", {}), g.get("tokens", {})
print(f"grid: {v.get('accepted', 0)}/{v.get('run', 0)} segment proofs verified; ids "
      f"{tk.get('prompt_positions', 0)} prompt + {tk.get('generated_positions', 0)} generated, "
      f"{len(tk.get('mismatches') or [])} wrong, "
      f"{len(tk.get('unbacked') or [])} with no argmax behind them")
if not v.get("all", True):
    bad.append(f"{v.get('run', 0) - v.get('accepted', 0)} segment proof(s) did not verify")
if not tk.get("all", True):
    bad.append(f"the published ids do not chain: {tk.get('mismatches')}, "
               f"unbacked {tk.get('unbacked')}")
if not model:
    bad.append("the grid compared no model root: it was given no manifest")
if n_bad_model or n_bad_pre:
    bad.append(f"{n_bad_model} model root(s) and {n_bad_pre} shape root(s) are not the "
               "manifest's")
if not g["all_chain"]:
    bad.append(f"the grid did not chain: {g['failures']}")
for u in g["unchecked_ends"]:
    print(f"unchecked end: {u['what']} -- {u['why']}")
if bad:
    sys.exit("; ".join(bad))
print("every segment's model root is the published commitment's, and every shape root is "
      "the table's")
GATEPY
st "done"
JOBEOF
drv_start "$JOB"
rm -f "$JOB"
