#!/bin/sh
# synthetic-digests: the three sound synthetic segment shapes, on both backends.
#
#   tools/drivers/synthetic-digests.sh <host> <prover-commit> <harness-commit>
#
# `zk-prover compose` with no witness proves one small synthetic layer segment.
# Three such shapes are the prover's sound-default reference digests; they were
# recorded on the SIMD backend alone, and this run records them on the CUDA
# backend beside it.  A digest that is equal on both backends is the gate: the
# device kernels compute what the host builders compute, cell for cell, or the
# proof is a different proof.
#
# The device kernels are generated per segment shape, so the run emits them for
# the three shapes into one store, installs them into the vendored fork and
# rebuilds the CUDA backend before proving.  An installed tree differs from its
# commit, so the job marks it dirty and the manifest records that.
#
# A synthetic segment carries no witness, so nothing here runs the harness; the
# harness commit is pushed and pinned so the manifest names the pair.
#
# The first call pushes zk-prover at the two commits to the host, starts the
# job detached and prints the poll command.  Every later call with the same
# arguments prints the status; once the status says done it fetches the
# outputs into runs/<run-id>/, writes manifest.json from the prover's
# provenance block, and runs check.py.  Nothing measured is typed in here.
#
# Host time: about 10 minutes of building per backend, then seconds per proof.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=synthetic-digests

# ---- the configuration: here and in the manifest, nowhere else ---------------
SYN="--round away --variants intsplit6 --table-bits 16 --s 32 --ctx 128 --hd 32"
RESIDUAL_STREAM="--nout 64 --residual-stream-a 32 --kmax 16 --synth-residual-stream"
GKR5="--gkr-bands --gkr-dequant --gkr-residual-stream --gkr-freivalds --gkr-attnout"
# one line per shape: <name> <flags after $SYN>.  No skip flag anywhere.
SHAPES="sound|--bands 2,1 $RESIDUAL_STREAM --corner
sound_gkrfive|--bands 2,1 $RESIDUAL_STREAM --corner $GKR5
sound_aligned|--bands 2,2 --nin 128 --nout 128 --residual-stream-a 32 --kmax 16 --synth-residual-stream --corner"
KERNEL_FAMILIES=b65_chan_eval,b65_key_eval,b65_row_eval,b65_attn_out_eval,b65_dequant_eval,b65_freivalds_eval,b65_exp_table_eval,b65_table_eval,b65_residual_stream_eval,b65_residual_stream_table_eval

status() { ssh -o BatchMode=yes "$HOST" "cat ~/runs/$NAME.status 2>/dev/null || true"; }

# ---- finish: fetch, manifest, check ------------------------------------------
ST=$(status)
case "$ST" in
  *"done exit=0"*)
    TMP=$(mktemp -d "$ROOT/runs/.fetch-$NAME.XXXXXX")
    "$ROOT/tools/remote/fetch.sh" "$HOST" "$NAME" "$TMP"
    python3 "$HERE/lib/manifest.py" --driver "tools/drivers/$NAME.sh" --fetched "$TMP" \
        --runs "$ROOT/runs" --prover-commit "$PROVER" --harness-commit "$HARNESS" \
        --date "$(printf '%s\n' "$ST" | awk '/^done/ {print substr($3, 1, 10)}')"
    rmdir "$TMP" 2>/dev/null || true
    (cd "$ROOT" && python3 tools/constants/check.py)
    exit 0 ;;
  *"done exit="*)
    echo "$NAME on $HOST failed: $ST"; echo "log: ssh $HOST tail -50 '~/runs/$NAME.log'"; exit 1 ;;
  running*)
    echo "$NAME on $HOST: $ST"; echo "poll: ssh $HOST cat '~/runs/$NAME.status'"; exit 0 ;;
esac

# ---- start: push the pinned sources, then the job ----------------------------
# a git directory, not a `.git` directory: a linked work tree has a `.git` file
git -C "$ZK_PROVER" rev-parse --git-dir >/dev/null 2>&1 ||
  { echo "no zk-prover clone at $ZK_PROVER (set ZK_PROVER_DIR)" >&2; exit 2; }
git -C "$ZK_PROVER" cat-file -e "$PROVER^{commit}" || { echo "unknown prover commit $PROVER" >&2; exit 2; }
git -C "$ZK_PROVER" cat-file -e "$HARNESS^{commit}" || { echo "unknown harness commit $HARNESS" >&2; exit 2; }
"$ROOT/tools/remote/push.sh" "$HOST" "$ZK_PROVER" "runs/$NAME/src" "$PROVER"
"$ROOT/tools/remote/push.sh" "$HOST" "$ZK_PROVER" "runs/$NAME/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
R=\$HOME/runs/$NAME
SRC=\$R/src
OUT=\$R/out; GEN=\$R/gen
mkdir -p \$OUT \$GEN
st() { echo "\$(date -u +%H:%M:%S) \$*"; }

# CUDA: the fork's build script hardcodes /usr/local/cuda/lib64; the binaries link libcudart
for d in \${CUDA_HOME:-} \$HOME/cuda-12.9 /usr/local/cuda-12.9 /usr/local/cuda; do
  [ -n "\$d" ] && [ -x "\$d/bin/nvcc" ] && CUDA_HOME=\$d && break
done
export CUDA_HOME PATH="\$CUDA_HOME/bin:\$HOME/.cargo/bin:\$PATH" LD_LIBRARY_PATH="\$CUDA_HOME/lib64:\${LD_LIBRARY_PATH:-}"
export CUDAARCHS=\${CUDAARCHS:-90} CUDAHOSTCXX=\${CUDAHOSTCXX:-\$(command -v g++-14 || command -v g++)}
export RAYON_NUM_THREADS=\${RAYON_NUM_THREADS:-4}

# the configuration, for the manifest
cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "witness": "none: synthetic segments",
 "shared_flags": "$SYN",
 "shapes": {"sound": "--bands 2,1 $RESIDUAL_STREAM --corner",
            "sound_gkrfive": "--bands 2,1 $RESIDUAL_STREAM --corner $GKR5",
            "sound_aligned": "--bands 2,2 --nin 128 --nout 128 --residual-stream-a 32 --kmax 16 --synth-residual-stream --corner"}}
CFG

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
st "nvcc: \$(nvcc --version | tail -2 | head -1)"

# 1. the SIMD backend of the pinned prover commit, and the three proofs it makes
st "build: simd"
( cd \$SRC && CARGO_TARGET_DIR=\$R/t-simd cargo build --release --locked )
SIMD=\$R/t-simd/release/zk-prover
printf '%s\n' "$SHAPES" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  st "simd: \$name"
  \$SIMD compose $SYN \$flags > \$OUT/\$name-simd.json 2> \$R/\$name-simd.err
done

# 2. the device kernels for the three shapes, into one store, installed into the fork
K=\$SRC/prover/kernels
[ -d \$K ] || { st "no prover/kernels in this prover commit; the CUDA backend would evaluate constraints on the CPU"; exit 3; }
printf '%s\n' "$SHAPES" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  st "emit: \$name"
  \$SIMD cudaemit $SYN \$flags --out \$GEN --block 256 --min-blocks 2 > /dev/null
  \$SIMD genemit $SYN \$flags --families "$KERNEL_FAMILIES" --out \$GEN > /dev/null
done
python3 \$K/m2b_kernels.py --fork \$SRC/nitroo --gen \$GEN
python3 \$K/m4b_kernels.py --fork \$SRC/nitroo --gen \$GEN --src \$K
find \$SRC/nitroo/crates/stwo/src/stwo_cuda/cuda \( -name '*.cu' -o -name '*.cuh' \) -exec touch {} +
cp \$GEN/cudakernels.rs \$GEN/gencudakernels.rs \$SRC/prover/src/
# an installed tree is no longer the commit that was pushed, and says so
grep -q ' dirty\$' \$SRC/.source-commit || sed -i 's/\$/ dirty/' \$SRC/.source-commit
st "kernels installed"

# 3. the CUDA backend of the same commit, with the store compiled in, and its proofs
st "build: cuda"
( cd \$SRC && CARGO_TARGET_DIR=\$R/t-cuda cargo build --release --locked -p zk-prover --features cuda )
CUDA=\$R/t-cuda/release/zk-prover
printf '%s\n' "$SHAPES" | while IFS='|' read -r name flags; do
  [ -n "\$name" ] || continue
  st "cuda: \$name"
  \$CUDA compose $SYN \$flags > \$OUT/\$name-cuda.json 2> \$R/\$name-cuda.err
  grep -c 'kernel fallback:' \$R/\$name-cuda.err > \$OUT/\$name-cuda.fallbacks || true
done

# 4. the gate: the CUDA digest equals the SIMD digest, shape by shape
python3 - \$OUT <<'PY'
import json, sys, pathlib
out = pathlib.Path(sys.argv[1])
bad = []
for name in ("sound", "sound_gkrfive", "sound_aligned"):
    d = {}
    for b in ("simd", "cuda"):
        d[b] = json.loads((out / f"{name}-{b}.json").read_text())["result"]["point"]["proof_sha256"]
    print(f"{name}: simd {d['simd'][:16]} cuda {d['cuda'][:16]}")
    if d["simd"] != d["cuda"]:
        bad.append(name)
    n = int((out / f"{name}-cuda.fallbacks").read_text().strip())
    print(f"{name}: kernel fallback lines on the CUDA backend: {n}")
    if n:
        bad.append(name + " (fallback)")
if bad:
    sys.exit("the two backends disagree: " + ", ".join(bad))
print("both backends agree on all three digests")
PY
st "done"
JOBEOF
ssh -o BatchMode=yes "$HOST" "mkdir -p ~/runs/$NAME && cat > ~/runs/$NAME/job.sh" < "$JOB"
rm -f "$JOB"
"$ROOT/tools/remote/run.sh" "$HOST" "$NAME" "sh \$HOME/runs/$NAME/job.sh"
echo "when the status says done, run this command again with the same arguments"
