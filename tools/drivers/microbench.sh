#!/bin/sh
# microbench: what the proof system charges per cell, per lookup and per hash.
#
#   tools/drivers/microbench.sh <host> <prover-commit> <harness-commit>
#
# The cost model prices a proof from measured rates and a cell count, and every
# rate it reads is an input this run makes.  Three kinds of measurement, and
# they are different kinds:
#
#   1. One composed synthetic segment on the reference backend.  `compose` is
#      the only subcommand of the prover that makes a proof and therefore the
#      only one that writes a binding table, so it is what makes this run
#      admissible at all; and its phase timings against its own committed cell
#      count split the proof into its commitment part and its FRI part.  The
#      card's own commitment rate is not measured here and does not need to be:
#      a sequence run measures it on real segments at a real context, which is
#      what `rate.headline.c4096.commit` already is.
#   2. The cell-cost subcommands on the SIMD backend: what one dequantized
#      accumulator, one requantized value, one residual-stream operation, one
#      argmax comparison and one packed attention instance cost in committed
#      cells.  A cell count is the same on both backends; the SIMD backend is
#      the reference, so that is where they are read.
#   3. The vendored library's own benchmarks of the primitives underneath:
#      field operations, the lookup argument, the Merkle commitment, FRI's
#      folding step and a whole polynomial commitment.  These run on the host's
#      cores and use no card.
#
# What this run does not measure, because nothing at this prover commit
# produces it: the cells per weight of a Freivalds check, the marginal cells of
# one lookup, and the attention cells per head, key and token.  The cost model
# reads those from files a retired benchmark tree wrote, and no subcommand
# writes them today; the campaign's pull request names them.
#
# The first call pushes zk-prover at the two commits to the host, starts the
# job detached and prints the poll command.  Every later call with the same
# arguments prints the status; once the status says done it fetches the
# outputs into runs/<run-id>/, writes manifest.json from the prover's
# provenance block, and runs check.py.  Nothing measured is typed in here.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
HOST=${1:?host alias}; PROVER=${2:?prover commit}; HARNESS=${3:?harness commit}
ZK_PROVER=${ZK_PROVER_DIR:-$ROOT/../zk-prover}     # a local clone to archive the commits from
NAME=microbench
. "$HERE/lib/driver.sh"

# ---- the configuration: here and in the manifest, nowhere else ---------------
LABEL=microbench           # an input to the cost model, not a configuration the paper cites
# The composed segment: the prover's recorded sound synthetic shape, with the
# five GKR reductions on because that is the paper's configuration.
ARITH="--round away --variants intsplit6 --table-bits 16"
SHAPE="--s 32 --ctx 128 --hd 32 --head-groups 2,2 --nin 128 --nout 128 --residual-stream-a 32 --kmax 16 --synth-residual-stream --diagonal-block"
GKR="--gkr-key-tiles --gkr-dequant --gkr-residual-stream --gkr-freivalds --gkr-attnout"
# The cell-cost subcommands, one line each: <output name>|<subcommand and flags>
CELL_COSTS='b6-dequant|dequant --n 1048576 --per-row 16 --variants limbs,round,pow2,chain,int8 --round even
b6-pack|pack --s 512 --ctx 1024 --hd 64 --insts 1,2,4,8,16 --variants intexp
b65-requant|requant --round even
b65-residual-stream|residual-stream --rows 4096 --leaves 32 --per-row 16 --kmax 18 --round even
b10-argmax|argmax --tokens 8 --vocab 8192 --per-row 64
b3-width|width --n 1048576 --widths 4,8,16,32,64,128
b4-kmax|kmax --n 262144 --per-row 16 --kmax-sweep 10,12,14,16,18,21'
# The vendored library's benchmarks.  Bounded sampling: ten samples and five
# seconds of measurement per identifier is enough for a rate and keeps the run
# inside its half hour.
BENCHES="field fri lookups merkle pcs"
CRITERION_ARGS="--sample-size 10 --measurement-time 5 --warm-up-time 2"
XTHREADS=20

drv_finish "$(drv_status)"

# ---- start: push the pinned sources, then the job ----------------------------
drv_check_commits
BUILD=$(drv_build_root)
drv_push "$BUILD/src" "$PROVER"
drv_push "$BUILD/harness-src" "$HARNESS"

JOB=$(mktemp)
cat > "$JOB" <<JOBEOF
#!/bin/sh
# generated by $NAME.sh; runs on the host under tools/remote/run.sh
set -eu
B=\$HOME/$BUILD
R=\$HOME/runs/$NAME
SRC=\$B/src
OUT=\$R/out
mkdir -p \$OUT
$(drv_job_preamble)
export RAYON_NUM_THREADS=\${RAYON_NUM_THREADS:-$XTHREADS}

cat > \$OUT/config.json <<CFG
{"driver": "$NAME", "label": "$LABEL",
 "compose_arith": "$ARITH", "compose_shape": "$SHAPE", "compose_gkr": "$GKR",
 "benches": "$BENCHES", "criterion_args": "$CRITERION_ARGS",
 "threads": $XTHREADS,
 "witness": "synthetic, the prover's own fixed-seed generator; no model and no extraction"}
CFG

st "gpu: \$(nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader)"
st "cores: \$(nproc), threads \$RAYON_NUM_THREADS"

# 1. the reference backend of the pinned prover commit.  The vendored library
#    links its CUDA library on every Linux build, so the toolkit is needed here
#    too, but nothing in this run proves on the card.
st "build"
( cd \$SRC && CARGO_TARGET_DIR=\$B/t-simd cargo build --release --locked )
SIMD=\$B/t-simd/release/zk-prover

# 2. the composed segment: the run's binding table, and the commitment and FRI
#    parts of one proof against its own committed cell count.
if [ ! -s \$OUT/compose-simd.json ]; then
  st "compose on the reference backend"
  \$SIMD compose $ARITH $SHAPE $GKR > \$OUT/compose-simd.json 2> \$R/compose-simd.err
fi

# 3. the cell-cost subcommands, on the reference backend
printf '%s\n' '$CELL_COSTS' | while IFS='|' read -r out cmd; do
  [ -n "\$out" ] || continue
  if [ -s \$OUT/\$out.json ]; then st "\$out already run"; continue; fi
  st "\$out: \$cmd"
  if \$SIMD \$cmd > \$OUT/\$out.json 2> \$R/\$out.err; then
    st "\$out done"
  else
    rm -f \$OUT/\$out.json
    printf '%s\n' "\$out: \$cmd" >> \$OUT/refused.txt
    st "\$out did not run; recorded in out/refused.txt, see \$R/\$out.err"
  fi
done

# 4. the vendored library's benchmarks, on the host's cores.  A benchmark that
#    does not build or does not run is recorded and the run goes on: the cost
#    model reads each of these on its own.
for bench in $BENCHES; do
  if [ -s \$OUT/crit-\$bench.txt ]; then st "bench \$bench already run"; continue; fi
  st "bench: \$bench"
  if ( cd \$SRC/nitroo && RUSTFLAGS="-Awarnings -C target-cpu=native -C opt-level=3" \
        cargo bench -p stwo --bench \$bench --features prover -- $CRITERION_ARGS ) \
        > \$OUT/crit-\$bench.txt 2> \$R/crit-\$bench.err; then
    st "bench \$bench done"
  else
    rm -f \$OUT/crit-\$bench.txt
    printf '%s\n' "bench \$bench" >> \$OUT/refused.txt
    st "bench \$bench did not run; recorded in out/refused.txt, see \$R/crit-\$bench.err"
  fi
done
# criterion's own estimates, which are the machine-readable form the audit reads
if [ -d \$SRC/nitroo/target/criterion ]; then
  rm -rf \$OUT/criterion; mkdir -p \$OUT/criterion
  ( cd \$SRC/nitroo/target/criterion && find . -name estimates.json -path '*/new/*' -print0 \
      | tar --null -cf - -T - ) | tar -C \$OUT/criterion -xf -
  st "criterion estimates: \$(find \$OUT/criterion -name estimates.json | wc -l) files"
fi

# 5. what was measured, and the gate
python3 - \$OUT <<'PY'
import json, pathlib, sys
out = pathlib.Path(sys.argv[1])
bad, rows = [], {}
digests = {}
for tag in ("compose-simd",):
    f = out / f"{tag}.json"
    if not f.exists():
        bad.append(f"{tag}: the composed segment did not prove"); continue
    doc = json.loads(f.read_text())
    p, prov = doc["result"]["point"], doc["provenance"]
    digests[tag] = p["proof_sha256"]
    ph = p["phases"]
    rows[tag] = {"backend": prov["backend"], "accepts": p["accepts"],
                 "fresh_cells": p["cells"]["fresh"],
                 "commit_secs": ph["commit_secs"], "fri_secs": ph["fri_secs"],
                 "prove_call_secs": ph["prove_call_secs"],
                 "stwo_total_secs": ph["commit_secs"] + ph["prove_call_secs"],
                 "wall_secs": ph["wall_secs"],
                 "unsound_skips": prov["unsound_skips"],
                 "all_bound": prov["binding"]["all_bound"],
                 "unbound": prov["binding"]["unbound"]}
    print(f"{tag}: {p['cells']['fresh']:,} fresh cells, commit {ph['commit_secs']:.3f} s, "
          f"fri {ph['fri_secs']:.3f} s, accepts {p['accepts']}, "
          f"skips {prov['unsound_skips'] or 'none'}, unbound {prov['binding']['unbound']}")
    if not p["accepts"]:
        bad.append(f"{tag}: the proof was rejected")
    if prov["unsound_skips"]:
        bad.append(f"{tag}: unsound skips in effect")
made = sorted(f.name for f in out.glob("*.json"))
crit = sorted(p.parent.parent.name for p in out.glob("criterion/**/new/estimates.json"))
refused = (out / "refused.txt").read_text().split("\n") if (out / "refused.txt").exists() else []
json.dump({"compose": rows, "digests": digests, "outputs": made,
           "criterion_ids": crit, "refused": [r for r in refused if r]},
          open(out / "summary.json", "w"), indent=1)
print(f"{len(made)} JSON outputs, {len(crit)} benchmark identifiers, "
      f"{len([r for r in refused if r])} refused")
if bad:
    sys.exit("; ".join(bad))
print("the composed segment accepts; no skip in effect")
PY
st "done"
JOBEOF
drv_start "$JOB"
rm -f "$JOB"
