#!/usr/bin/env python3
"""Write `INDEX.md` from the run manifests and `constants.json`: run id, driver,
GPU as reported, the number of unsound skips, and the constants it backs.

    python3 tools/constants/index.py [--check]     (--check: fail if INDEX.md is stale)
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from constants import load  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]


def render():
    backed = {}
    for k, e in load()["constants"].items():
        if e.get("run"):
            backed.setdefault(e["run"], []).append(k)
    rows = ["# Runs", "", "Generated by `tools/constants/index.py`; do not edit.", "",
            "| run id | driver | GPU | unsound skips | constants backed |", "|---|---|---|---|---|"]
    for m in sorted(ROOT.glob("runs/*/manifest.json")):
        d = json.loads(m.read_text())
        keys = backed.pop(d["run_id"], [])
        rows.append(f"| `{d['run_id']}` | `{d['driver']}` | {d.get('gpu')} | {len(d.get('unsound_skips', []))} | "
                    + (", ".join(f"`{k}`" for k in sorted(keys)) or "none yet") + " |")
    for run, keys in sorted(backed.items()):
        rows.append(f"| `{run}` | **no manifest** | | | {', '.join(f'`{k}`' for k in sorted(keys))} |")
    return "\n".join(rows) + "\n"


def main(argv):
    text = render()
    path = ROOT / "INDEX.md"
    if "--check" in argv:
        if path.exists() and path.read_text() == text:
            print("index.py: INDEX.md is current")
            return 0
        print("index.py: INDEX.md is stale; run tools/constants/index.py")
        return 1
    path.write_text(text)
    print(f"index.py: wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
