#!/usr/bin/env python3
"""Write the paper's interface: a LaTeX macros file and a markdown table.

    python3 tools/constants/export.py [OUTDIR]     (default: export/)

One `\\newcommand` per constant, the key as the macro name with `.` and `_`
dropped, each part capitalised and digits spelled out, since LaTeX macro names
carry letters only.  Refuses to run while `discrepancies` is non-empty.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from constants import load  # noqa: E402

DIGITS = "Zero One Two Three Four Five Six Seven Eight Nine".split()


def macro(key):
    out = []
    for part in key.replace("_", ".").split("."):
        if part:
            spelled = "".join(DIGITS[int(ch)] if ch.isdigit() else ch for ch in part)
            out.append(spelled[0].upper() + spelled[1:])
    return "".join(out)


def main(argv):
    doc = load()
    if doc["discrepancies"]:
        sys.exit(f"export.py: {len(doc['discrepancies'])} open discrepancies; export waits until none")
    out = pathlib.Path(argv[0] if argv else "export")
    out.mkdir(parents=True, exist_ok=True)
    c = doc["constants"]
    tex = ["% generated by tools/constants/export.py; do not edit"]
    md = ["| key | value | unit | card | context | timing scope | grade | run |", "|---|---|---|---|---|---|---|---|"]
    for k in sorted(c):
        e = c[k]
        val = e["value"]
        tex.append(f"\\newcommand{{\\{macro(k)}}}{{{val}}}")
        md.append(f"| `{k}` | {val} | {e['unit']} | {e['card']} | {e['context']} | {e['timing_scope']} | {e['grade']} | {e.get('run', '')} |")
    (out / "constants.tex").write_text("\n".join(tex) + "\n")
    (out / "constants.md").write_text("\n".join(md) + "\n")
    print(f"export.py: {len(c)} constants -> {out}/constants.tex, {out}/constants.md")


if __name__ == "__main__":
    main(sys.argv[1:])
